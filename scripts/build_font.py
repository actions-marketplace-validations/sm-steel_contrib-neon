"""Builds src/render/font.ts: an ASCII subset of Monaspace Neon as base64 WOFF2.

The OFL reserves the name "Monaspace", so the subset (a Modified Version) is
renamed. Copyright and license name records are kept inside the font.

Run: uv run scripts/build_font.py   (after npm ci)
"""

import base64
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "node_modules/@fontsource/monaspace-neon/files/monaspace-neon-latin-400-normal.woff2"
FAMILY = "ContribNeon Mono"
OUT = ROOT / "src/render/font.ts"

# Printable ASCII covers the HUD text and every valid GitHub login.
CODEPOINTS = list(range(0x20, 0x7F))

font = TTFont(SOURCE)
options = subset.Options()
options.flavor = "woff2"
options.layout_features = []  # no ligatures/texture healing needed for a HUD line
options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
subsetter = subset.Subsetter(options)
subsetter.populate(unicodes=CODEPOINTS)
subsetter.subset(font)

missing = [hex(c) for c in CODEPOINTS if c not in font.getBestCmap()]
if missing:
    print(f"warning: glyphs missing from source: {missing}")

names = font["name"]
for rec in list(names.names):
    if rec.nameID in (1, 3, 4, 6, 16, 17):
        names.removeNames(nameID=rec.nameID)
names.setName(FAMILY, 1, 3, 1, 0x409)
names.setName(f"{FAMILY} Regular", 4, 3, 1, 0x409)
names.setName(FAMILY.replace(" ", "") + "-Regular", 6, 3, 1, 0x409)
names.setName(f"{FAMILY} Regular; subset of Monaspace Neon", 3, 3, 1, 0x409)

buf = BytesIO()
font.flavor = "woff2"
font.save(buf)
data = base64.b64encode(buf.getvalue()).decode()

OUT.write_text(
    "// Generated by scripts/build_font.py: do not edit.\n"
    "// ASCII subset of Monaspace Neon (c) 2023 GitHub, SIL Open Font License 1.1,\n"
    '// renamed per the OFL Reserved Font Name clause. See fonts/OFL.txt.\n'
    f'export const FONT_FAMILY = "{FAMILY}";\n'
    f'export const FONT_WOFF2 = "{data}";\n',
    encoding="utf-8",
)
print(f"wrote {OUT.relative_to(ROOT)} ({len(buf.getvalue())} bytes woff2)")
